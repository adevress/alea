#include "nanobench.h"

#include <chrono>
#include <cstddef>
#include <cstdint>
#include <random>
#include <span>
#include <vector>

#include "alea/hash.hpp"

//
// Throughput comparison of the alea hashes over a single 1 MiB message.
// One benchmarked operation hashes the whole message, so the reported
// operations per second are directly the number of MiB hashed per second.
//

namespace {

constexpr std::size_t message_size = 1024 * 1024;

std::vector<std::byte> make_message() {
  std::vector<std::byte> message(message_size);
  std::mt19937_64 rng(0x9e3779b97f4a7c15ull);
  std::uniform_int_distribution<unsigned int> byte(0, 255);
  for (std::size_t i = 0; i < message.size(); ++i) {
    message[i] = static_cast<std::byte>(byte(rng));
  }
  return message;
}

template <typename Hasher>
void add_hash_bench(ankerl::nanobench::Bench& bench, const char* name, std::span<const std::byte> message) {
  bench.run(name, [&] {
    Hasher hasher;
    hasher.update(message);
    const typename Hasher::digest_type digest = hasher.finalize();
    std::uint64_t sink = 0;
    for (const std::byte value : digest) {
      sink += std::to_integer<std::uint64_t>(value);
    }
    ankerl::nanobench::doNotOptimizeAway(sink);
  });
}

} // namespace

int main() {
  const std::vector<std::byte> message = make_message();

  ankerl::nanobench::Bench bench;
  bench.title("alea -- hash throughput over one 1 MiB message (op/s = MiB/s)");
  bench.warmup(2);
  bench.minEpochTime(std::chrono::milliseconds(100));

  add_hash_bench<alea::blake2b>(bench, "alea::blake2b", message);
  add_hash_bench<alea::blake2s>(bench, "alea::blake2s", message);
  add_hash_bench<alea::sha256>(bench, "alea::sha256 ", message);
}
