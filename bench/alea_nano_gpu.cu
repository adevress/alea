#include "nanobench.h"

#include <chrono>
#include <cstddef>
#include <cstdint>
#include <cuda_runtime.h>
#include <curand_kernel.h>
#include <stdexcept>
#include <string>

#include "alea/random.hpp"

//
// CUDA benchmark of the alea generators.
//
// The benchmark runs the very same single source headers as the host
// benchmark, compiled by nvcc. Each measurement launches a single block of 256
// threads, and every thread generates `work` counter blocks through
// counter_engine<CBRNG>.
//
// NVIDIA ships its own Philox4x32-10 implementation with the CUDA toolkit, in
// <curand_kernel.h> (stateful API) and <curand_philox4x32_x.h> (raw rounds).
// The `Nvidia philox` case runs it with the exact same setup as
// alea::philox4x32 so that the two implementations can be compared directly.
//
// The result buffer uses the CUDA unified memory model (cudaMallocManaged):
// the kernel writes it and the host reads it transparently, without any
// explicit cudaMemcpy. Right after the benchmark, one word of the buffer is
// picked with a std::chrono based random index and consumed by the host. The
// index is only known at run time, so neither nvcc nor the host compiler can
// prove which part of the buffer is observed and eliminate the generation.
//

namespace {

void check_cuda(cudaError_t code, const char* expr, const char* file, int line) {
  if (code != cudaSuccess) {
    throw std::runtime_error(std::string("CUDA error: ") + cudaGetErrorString(code) + " (" + expr + ") at " + file +
                             ":" + std::to_string(line));
  }
}

#define ALEA_CUDA_CHECK(expr) check_cuda((expr), #expr, __FILE__, __LINE__)

struct launch_config {
  unsigned blocks;
  unsigned threads;
};

/// the benchmark runs a single block of 256 threads
launch_config bench_config() { return launch_config{1u, 256u}; }

/// deterministic key derived from a linear index, reproducible on host and device
template <typename CBRNG> ALEA_HOST_DEVICE typename CBRNG::key_type make_key(std::uint64_t seed) {
  typename CBRNG::key_type key{};
  std::uint64_t state = seed + UINT64_C(0x9E3779B97F4A7C15);
  for (std::size_t i = 0; i < key.size(); ++i) {
    state += UINT64_C(0x9E3779B97F4A7C15);
    std::uint64_t z = state;
    z = (z ^ (z >> 30)) * UINT64_C(0xBF58476D1CE4E5B9);
    z = (z ^ (z >> 27)) * UINT64_C(0x94D049BB133111EB);
    key[i] = static_cast<typename CBRNG::uint_type>(z ^ (z >> 31));
  }
  return key;
}

/// every thread encrypts `work` counter blocks and folds them into a checksum
template <typename CBRNG> __global__ void throughput_kernel(unsigned long long* out, unsigned work) {
  const std::size_t i = static_cast<std::size_t>(blockIdx.x) * blockDim.x + threadIdx.x;
  alea::counter_engine<CBRNG> engine(make_key<CBRNG>(i));

  unsigned long long acc = 0;
  for (unsigned w = 0; w < work; ++w) {
    const typename CBRNG::domain_type block = engine.generate_block();
    for (const auto word : block) {
      acc ^= static_cast<unsigned long long>(word);
    }
  }
  out[i] = acc;
}

/// benchmark CBRNG on a single block of 256 threads
///
/// the output buffer is allocated with the unified memory model and is read
/// back by the host without an explicit copy. A word picked with a clock based
/// random index is consumed after the benchmark: it validates that the kernel
/// actually produced the work and keeps the whole buffer observable, so
/// neither nvcc nor the host compiler can drop the computation
///
template <typename Launch> void run_bench(const launch_config& config, unsigned work, const char* name, Launch launch) {
  const std::size_t grid_size = static_cast<std::size_t>(config.blocks) * config.threads;

  // unified memory: the kernel stores the result, the host reads it back
  // transparently, no cudaMemcpy is involved
  unsigned long long* out = nullptr;
  ALEA_CUDA_CHECK(cudaMallocManaged(&out, grid_size * sizeof(unsigned long long)));

  // clock based index, only known at run time: the compilers cannot tell which
  // word is observed and therefore cannot eliminate the generation
  const std::size_t random_index =
      static_cast<std::size_t>(std::chrono::steady_clock::now().time_since_epoch().count()) % grid_size;

  ankerl::nanobench::Bench bench;
  bench.title("alea GPU -- counter block throughput: threefry and philox variations");
  bench.warmup(1).minEpochTime(std::chrono::milliseconds(200));
  // one operation is the full `work` block loop of a single thread: a single
  // generated word is well below a nanosecond on a GPU, and this keeps the
  // fastest operation above 10 ns so that the columns are meaningful
  bench.batch(grid_size);
  bench.run(name, [&] {
    launch(out, work);
    ALEA_CUDA_CHECK(cudaGetLastError());
    ALEA_CUDA_CHECK(cudaDeviceSynchronize());
  });

  // read a random word back through the unified memory model: this is a plain
  // host load that makes the whole buffer observable
  ankerl::nanobench::doNotOptimizeAway(out[random_index]);

  ALEA_CUDA_CHECK(cudaFree(out));
}

/// benchmark one alea CBRNG
///
/// `work` counter blocks per thread, one block of 256 threads, unified memory
/// and the clock based random read, exactly like the `Nvidia philox` case
template <typename CBRNG> void bench_generator(const launch_config& config, unsigned work, const char* name) {
  run_bench(config, work, name, [&config](unsigned long long* out, unsigned work) {
    throughput_kernel<CBRNG><<<config.blocks, config.threads>>>(out, work);
  });
}

/// NVIDIA CURAND Philox4x32-10: one state per thread and `work` calls to
/// curand4, each returning four 32-bit words folded into a checksum
///
/// this is the exact counterpart of alea::philox4x32: same launch geometry,
/// same number of generated words and same checksum fold
__global__ void nvidia_philox_kernel(unsigned long long* out, unsigned work) {
  const std::size_t i = static_cast<std::size_t>(blockIdx.x) * blockDim.x + threadIdx.x;
  curandStatePhilox4_32_10_t state;
  // every thread gets its own subsequence, the counterpart of the per-index
  // key derived by alea's make_key
  curand_init(0u, i, 0u, &state);

  unsigned long long acc = 0;
  for (unsigned w = 0; w < work; ++w) {
    const uint4 block = curand4(&state);
    acc ^= static_cast<unsigned long long>(block.x);
    acc ^= static_cast<unsigned long long>(block.y);
    acc ^= static_cast<unsigned long long>(block.z);
    acc ^= static_cast<unsigned long long>(block.w);
  }
  out[i] = acc;
}

/// benchmark NVIDIA CURAND's Philox4x32-10 with the same setup as alea
void bench_nvidia_philox(const launch_config& config, unsigned work, const char* name) {
  run_bench(config, work, name, [&config](unsigned long long* out, unsigned work) {
    nvidia_philox_kernel<<<config.blocks, config.threads>>>(out, work);
  });
}

} // namespace

int main() {
  const launch_config config = bench_config();
  // enough work per thread that one operation stays well above the timer
  // granularity: see the comment at the top of the file
  const unsigned work = 4096;

  bench_generator<alea::threefry2x32>(config, work, "alea::threefry2x32/20");
  bench_generator<alea::threefry4x32>(config, work, "alea::threefry4x32/20");
  bench_generator<alea::threefry2x64>(config, work, "alea::threefry2x64/20");
  bench_generator<alea::threefry4x64>(config, work, "alea::threefry4x64/20");

  bench_generator<alea::philox2x32>(config, work, "alea::philox2x32/10  ");
  bench_generator<alea::philox4x32>(config, work, "alea::philox4x32/10  ");
  bench_nvidia_philox(config, work, "Nvidia philox/10    ");
  bench_generator<alea::philox2x64>(config, work, "alea::philox2x64/10  ");
  bench_generator<alea::philox4x64>(config, work, "alea::philox4x64/10  ");
}