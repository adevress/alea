#include "nanobench.h"

#include <chrono>
#include <cstddef>
#include <cstdint>
#include <random>
#include <string>

#include "alea/random.hpp"

namespace alea {

// the threefry generators come in four word configurations (2 or 4 words of
// 32 or 64 bits) and, like the reference random123 package, in two round
// variants: the 20 rounds default ("secure") and a reduced 8 rounds variant
// ("fast", not cryptographically secure)
using threefry2x32_8 = threefry<2, std::uint32_t, 8>;
using threefry4x32_8 = threefry<4, std::uint32_t, 8>;
using threefry2x64_8 = threefry<2, std::uint64_t, 8>;
using threefry4x64_8 = threefry<4, std::uint64_t, 8>;

// ARS is a single 128 bit block generator: the reference ars4x32 uses 7
// rounds, the KAT vectors of the reference use 10. Both are benchmarked
using ars4x32_10 = ars<10>;

} // namespace alea

namespace {

// number of random values drawn at each invocation of a benchmarked lambda
const std::size_t values_per_call = 1000;

// sum `count` consecutive values returned by the engine `engine`
//
// the raw generation pipe line: this measures the throughput of the stream
// of random values, without any distribution overhead
template <typename Engine> std::uint64_t sum_raw(std::size_t count) {
  Engine engine;
  std::uint64_t val = 0;
  for (std::size_t i = 0; i < count; ++i) {
    val += engine();
  }
  return val;
}

// draw `count` values through the STL uniform distribution, the way an
// engine is consumed by most scientific code bases
//
// the distribution is sized to the word width of the engine: uint64 for
// the 64 bits engines, uint32 for the 32 bits ones
template <typename Engine> std::uint64_t sum_uniform(std::size_t count) {
  Engine engine;
  std::uniform_int_distribution<typename Engine::result_type> dist;
  std::uint64_t val = 0;
  for (std::size_t i = 0; i < count; ++i) {
    val += dist(engine);
  }
  return val;
}

// draw `count` values of the standard normal distribution (mean 0,
// variance 1) with the engine `engine`
template <typename Engine> double sum_gaussian(std::size_t count) {
  Engine engine;
  std::normal_distribution<double> dist;
  double val = 0;
  for (std::size_t i = 0; i < count; ++i) {
    val += dist(engine);
  }
  return val;
}

// sum the whole `count` blocks generated by the counter engine `Engine`
//
// counter based generators are often consumed in batch mode, where the
// encrypted counter block is grabbed as a whole instead of value per value
template <typename CBRNG> std::uint64_t sum_blocks(std::size_t count) {
  alea::counter_engine<CBRNG> engine;
  std::uint64_t val = 0;
  for (std::size_t i = 0; i < count; ++i) {
    const auto block = engine.generate_block();
    for (const auto word : block) {
      val += word;
    }
  }
  return val;
}

// register a raw stream throughput benchmark on the engine `Engine`
template <typename Engine> void add_raw_bench(ankerl::nanobench::Bench& bench, const std::string& name) {
  bench.minEpochIterations(1 << 14).run(name.c_str(), [&] {
    const std::uint64_t val = sum_raw<Engine>(values_per_call);
    ankerl::nanobench::doNotOptimizeAway(val);
  });
}

// register a uniform distribution benchmark on the engine `Engine`
template <typename Engine> void add_uniform_bench(ankerl::nanobench::Bench& bench, const std::string& name) {
  bench.minEpochIterations(1 << 14).run(name.c_str(), [&] {
    const std::uint64_t val = sum_uniform<Engine>(values_per_call);
    ankerl::nanobench::doNotOptimizeAway(val);
  });
}

// register a gaussian distribution benchmark on the engine `Engine`
template <typename Engine> void add_gaussian_bench(ankerl::nanobench::Bench& bench, const std::string& name) {
  bench.minEpochIterations(1 << 14).run(name.c_str(), [&] {
    const double val = sum_gaussian<Engine>(values_per_call);
    ankerl::nanobench::doNotOptimizeAway(val);
  });
}

// register a whole block benchmark on the counter based generator `CBRNG`
//
// the batch is the number of words drawn per block, so that the columns of
// the table stay comparable with the other benchmark families
// (one unit = one generated random value)
template <typename CBRNG> void add_block_bench(ankerl::nanobench::Bench& bench, const std::string& name) {
  using domain_type = typename CBRNG::domain_type;
  bench.batch(values_per_call * domain_type{}.size()).minEpochIterations(1 << 14).run(name.c_str(), [&] {
    const std::uint64_t val = sum_blocks<CBRNG>(values_per_call);
    ankerl::nanobench::doNotOptimizeAway(val);
  });
}

// configure the benches: one table per benchmark family, one unit is one
// generated random value (1000 values are drawn at each lambda call)
ankerl::nanobench::Bench make_bench(const std::string& title) {
  ankerl::nanobench::Bench bench;
  bench.title(title.c_str());
  bench.warmup(2).minEpochTime(std::chrono::milliseconds(50));
  bench.batch(values_per_call);
  return bench;
}

} // namespace

int main() {
  // raw per-value throughput: the stream of raw engine outputs, the pipe
  // line common to every use of the engines
  {
    ankerl::nanobench::Bench bench =
        make_bench("alea -- raw stream throughput: threefry and philox variations vs the STL generators");

    add_raw_bench<std::mt19937_64>(bench, "std::mt19937_64 ");
    add_raw_bench<std::mt19937>(bench, "std::mt19937     ");
    add_raw_bench<std::ranlux48>(bench, "std::ranlux48   ");

    add_raw_bench<alea::counter_engine<alea::threefry2x32_8>>(bench, "alea::threefry2x32/8  ");
    add_raw_bench<alea::counter_engine<alea::threefry2x32>>(bench, "alea::threefry2x32/20 ");
    add_raw_bench<alea::counter_engine<alea::threefry4x32_8>>(bench, "alea::threefry4x32/8  ");
    add_raw_bench<alea::counter_engine<alea::threefry4x32>>(bench, "alea::threefry4x32/20 ");
    add_raw_bench<alea::counter_engine<alea::threefry2x64_8>>(bench, "alea::threefry2x64/8  ");
    add_raw_bench<alea::counter_engine<alea::threefry2x64>>(bench, "alea::threefry2x64/20 ");
    add_raw_bench<alea::counter_engine<alea::threefry4x64_8>>(bench, "alea::threefry4x64/8  ");
    add_raw_bench<alea::counter_engine<alea::threefry4x64>>(bench, "alea::threefry4x64/20 ");

    add_raw_bench<alea::counter_engine<alea::philox2x32>>(bench, "alea::philox2x32/10  ");
    add_raw_bench<alea::counter_engine<alea::philox4x32>>(bench, "alea::philox4x32/10  ");
    add_raw_bench<alea::counter_engine<alea::philox2x64>>(bench, "alea::philox2x64/10  ");
    add_raw_bench<alea::counter_engine<alea::philox4x64>>(bench, "alea::philox4x64/10  ");

    add_raw_bench<alea::counter_engine<alea::ars4x32>>(bench, "alea::ars4x32/7   ");
    add_raw_bench<alea::counter_engine<alea::ars4x32_10>>(bench, "alea::ars4x32/10  ");
  }

  // the STL uniform distribution path, the typical way a generator is
  // consumed by scientific code: uint64 values for the 64 bits engines,
  // uint32 values for the 32 bits ones
  {
    ankerl::nanobench::Bench bench =
        make_bench("alea -- uniform distribution draws (uint64, uint32 for the 32 bits engines): threefry and philox "
                   "variations vs the STL generators");

    add_uniform_bench<std::mt19937_64>(bench, "std::mt19937_64 ");
    add_uniform_bench<std::mt19937>(bench, "std::mt19937     ");
    add_uniform_bench<std::ranlux48>(bench, "std::ranlux48   ");

    add_uniform_bench<alea::counter_engine<alea::threefry2x32_8>>(bench, "alea::threefry2x32/8  ");
    add_uniform_bench<alea::counter_engine<alea::threefry2x32>>(bench, "alea::threefry2x32/20 ");
    add_uniform_bench<alea::counter_engine<alea::threefry4x32_8>>(bench, "alea::threefry4x32/8  ");
    add_uniform_bench<alea::counter_engine<alea::threefry4x32>>(bench, "alea::threefry4x32/20 ");
    add_uniform_bench<alea::counter_engine<alea::threefry2x64_8>>(bench, "alea::threefry2x64/8  ");
    add_uniform_bench<alea::counter_engine<alea::threefry2x64>>(bench, "alea::threefry2x64/20 ");
    add_uniform_bench<alea::counter_engine<alea::threefry4x64_8>>(bench, "alea::threefry4x64/8  ");
    add_uniform_bench<alea::counter_engine<alea::threefry4x64>>(bench, "alea::threefry4x64/20 ");

    add_uniform_bench<alea::counter_engine<alea::philox2x32>>(bench, "alea::philox2x32/10  ");
    add_uniform_bench<alea::counter_engine<alea::philox4x32>>(bench, "alea::philox4x32/10  ");
    add_uniform_bench<alea::counter_engine<alea::philox2x64>>(bench, "alea::philox2x64/10  ");
    add_uniform_bench<alea::counter_engine<alea::philox4x64>>(bench, "alea::philox4x64/10  ");

    add_uniform_bench<alea::counter_engine<alea::ars4x32>>(bench, "alea::ars4x32/7   ");
    add_uniform_bench<alea::counter_engine<alea::ars4x32_10>>(bench, "alea::ars4x32/10  ");
  }

  // gaussian draws: the standard normal distribution, the work horse of
  // physics and statistics simulations
  {
    ankerl::nanobench::Bench bench =
        make_bench("alea -- gaussian draws (standard normal): threefry and philox variations vs the STL generators");

    add_gaussian_bench<std::mt19937_64>(bench, "std::mt19937_64 ");
    add_gaussian_bench<std::mt19937>(bench, "std::mt19937     ");
    add_gaussian_bench<std::ranlux48>(bench, "std::ranlux48   ");

    add_gaussian_bench<alea::counter_engine<alea::threefry2x32_8>>(bench, "alea::threefry2x32/8  ");
    add_gaussian_bench<alea::counter_engine<alea::threefry2x32>>(bench, "alea::threefry2x32/20 ");
    add_gaussian_bench<alea::counter_engine<alea::threefry4x32_8>>(bench, "alea::threefry4x32/8  ");
    add_gaussian_bench<alea::counter_engine<alea::threefry4x32>>(bench, "alea::threefry4x32/20 ");
    add_gaussian_bench<alea::counter_engine<alea::threefry2x64_8>>(bench, "alea::threefry2x64/8  ");
    add_gaussian_bench<alea::counter_engine<alea::threefry2x64>>(bench, "alea::threefry2x64/20 ");
    add_gaussian_bench<alea::counter_engine<alea::threefry4x64_8>>(bench, "alea::threefry4x64/8  ");
    add_gaussian_bench<alea::counter_engine<alea::threefry4x64>>(bench, "alea::threefry4x64/20 ");

    add_gaussian_bench<alea::counter_engine<alea::philox2x32>>(bench, "alea::philox2x32/10  ");
    add_gaussian_bench<alea::counter_engine<alea::philox4x32>>(bench, "alea::philox4x32/10  ");
    add_gaussian_bench<alea::counter_engine<alea::philox2x64>>(bench, "alea::philox2x64/10  ");
    add_gaussian_bench<alea::counter_engine<alea::philox4x64>>(bench, "alea::philox4x64/10  ");

    add_gaussian_bench<alea::counter_engine<alea::ars4x32>>(bench, "alea::ars4x32/7   ");
    add_gaussian_bench<alea::counter_engine<alea::ars4x32_10>>(bench, "alea::ars4x32/10  ");
  }

  // whole block usage of the counter engines, only possible with the
  // counter based generators
  {
    ankerl::nanobench::Bench bench =
        make_bench("alea -- whole counter block generation: the threefry and philox variations");

    add_block_bench<alea::threefry2x32_8>(bench, "alea::threefry2x32/8  ");
    add_block_bench<alea::threefry2x32>(bench, "alea::threefry2x32/20 ");
    add_block_bench<alea::threefry4x32_8>(bench, "alea::threefry4x32/8  ");
    add_block_bench<alea::threefry4x32>(bench, "alea::threefry4x32/20 ");
    add_block_bench<alea::threefry2x64_8>(bench, "alea::threefry2x64/8  ");
    add_block_bench<alea::threefry2x64>(bench, "alea::threefry2x64/20 ");
    add_block_bench<alea::threefry4x64_8>(bench, "alea::threefry4x64/8  ");
    add_block_bench<alea::threefry4x64>(bench, "alea::threefry4x64/20 ");

    add_block_bench<alea::philox2x32>(bench, "alea::philox2x32/10  ");
    add_block_bench<alea::philox4x32>(bench, "alea::philox4x32/10  ");
    add_block_bench<alea::philox2x64>(bench, "alea::philox2x64/10  ");
    add_block_bench<alea::philox4x64>(bench, "alea::philox4x64/10  ");

    add_block_bench<alea::ars4x32>(bench, "alea::ars4x32/7   ");
    add_block_bench<alea::ars4x32_10>(bench, "alea::ars4x32/10  ");
  }
}